#!/usr/bin/env python3
"""Generate a terrain-only reference world for the chunk oracle.

The world is generated by the reference server with three overrides applied
through a data pack:

* the overworld preset uses a single fixed biome instead of the multi-noise
  source, so no biome chooses eroded-badlands or frozen-ocean extensions;
* that biome declares no carvers and no features;
* the `minecraft:overworld` material rule is an empty sequence.

Structures are disabled through `server.properties`. The saved chunks
therefore contain exactly the output of the fill stage, which is what the
oracle test compares against.

Usage:
    generate.py --server-jar server.jar --seed 12345 --output /tmp/t2oracle

The reference server must be started by a JDK (Java 25 or newer for 26.3).
"""

