PACK_FORMAT = 121
REGION_CHUNKS = 3


def read_pack_data(server_jar: pathlib.Path, path: str) -> dict:
    """Read a JSON document from the versioned jar inside the bundler jar."""
    with zipfile.ZipFile(server_jar) as outer:
        version = json.loads(outer.read("version.json"))["id"]
        inner_name = f"META-INF/versions/{version}/server-{version}.jar"
        with zipfile.ZipFile(io.BytesIO(outer.read(inner_name))) as inner:
            return json.loads(inner.read(path))


def write_meta(pack: pathlib.Path) -> None:
    pack.mkdir(parents=True, exist_ok=True)
    (pack / "pack.mcmeta").write_text(
        json.dumps(
            {
                "pack": {
                    "description": "Terrain-only oracle",
                    "min_format": PACK_FORMAT,
                    "max_format": PACK_FORMAT,
                }
            }
        )
        + "\n"
    )


def read_pack_entries(server_jar: pathlib.Path, prefix: str) -> dict[str, dict]:
    """Read every JSON document under `prefix` from the versioned jar."""
    entries: dict[str, dict] = {}
    with zipfile.ZipFile(server_jar) as outer:
        version = json.loads(outer.read("version.json"))["id"]
        inner_name = f"META-INF/versions/{version}/server-{version}.jar"
        with zipfile.ZipFile(io.BytesIO(outer.read(inner_name))) as inner:
            for name in inner.namelist():
                if name.startswith(prefix) and name.endswith(".json"):
                    entries[name] = json.loads(inner.read(name))
    return entries


def write_pack(preset: dict, biome: dict, pack: pathlib.Path,
               empty_material_rule: bool, fixed_biome: str,
               biome_override: dict | None) -> None:
    write_meta(pack)

    preset["dimensions"]["minecraft:overworld"]["generator"][
        "biome_source"
    ] = {"type": "minecraft:fixed", "biome": fixed_biome}
    preset_dir = pack / "data/minecraft/worldgen/world_preset"
    preset_dir.mkdir(parents=True)
    (preset_dir / "normal.json").write_text(json.dumps(preset, indent=2) + "\n")

    if empty_material_rule:
        rules = pack / "data/minecraft/worldgen/material_rule"
        rules.mkdir(parents=True)
        (rules / "overworld.json").write_text(
            json.dumps({"type": "minecraft:sequence", "sequence": []}) + "\n"
        )

    biome["carvers"] = []
    biome["features"] = []
    biome_dir = pack / "data/oracle/worldgen/biome"
    biome_dir.mkdir(parents=True)
    (biome_dir / "terrain.json").write_text(json.dumps(biome, indent=2) + "\n")
    if biome_override is not None:
        namespace, path = fixed_biome.split(":", 1)
        override_dir = pack / "data" / namespace / "worldgen/biome"
        override_dir.mkdir(parents=True, exist_ok=True)
        (override_dir / f"{path.rsplit('/', 1)[-1]}.json").write_text(
            json.dumps(biome_override, indent=2) + "\n"
        )


def write_server_files(root: pathlib.Path, seed: int, port: int,
                       generate_structures: bool = False) -> None:
    (root / "server.properties").write_text(
        f"""level-name=world
level-seed={seed}
level-type=minecraft:normal
online-mode=false
sync-chunk-writes=true
view-distance=1
simulation-distance=1
spawn-protection=0
max-players=1
pause-when-empty-seconds=0
generate-structures={'true' if generate_structures else 'false'}
allow-nether=false
max-tick-time=-1
region-file-compression=deflate
server-port={port}
"""
    )
    (root / "eula.txt").write_text("eula=true\n")


def run_server(root: pathlib.Path, server_jar: pathlib.Path, settle: float) -> None:
    process = subprocess.Popen(
        ["java", "-Xms512M", "-Xmx2G", "-jar", str(server_jar), "nogui"],
        cwd=root,
        stdin=subprocess.PIPE,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
        bufsize=1,
    )
    lines: list[str] = []

    def drain() -> None:
        assert process.stdout is not None
        for line in process.stdout:
            lines.append(line)

    reader = threading.Thread(target=drain, daemon=True)
    reader.start()

    deadline = time.time() + 180
    while time.time() < deadline:
        if any("Done (" in line for line in lines):
            break
        if process.poll() is not None:
            break
        time.sleep(0.2)
    else:
        process.kill()
        raise SystemExit("the reference server did not start in time")

    assert process.stdin is not None
    process.stdin.write("gamerule randomTickSpeed 0\n")
    process.stdin.flush()
    span = REGION_CHUNKS * 16 - 1
    process.stdin.write(f"forceload add 0 0 {span} {span}\n")
    process.stdin.flush()
    time.sleep(settle)
    process.stdin.write("save-all flush\n")
    process.stdin.flush()
    time.sleep(6)
    process.stdin.write("stop\n")
    process.stdin.flush()
    try:
        process.wait(timeout=180)
    except subprocess.TimeoutExpired:
        process.kill()
    reader.join(timeout=5)


