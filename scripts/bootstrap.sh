# One-time developer/CI bootstrap for Refrain on Linux x86_64.
#
#   scripts/bootstrap.sh                 # full flow: profile + vendor + install + build + test
#   scripts/bootstrap.sh --profile-only  # only create the Conan profile (used by CI)
#   scripts/bootstrap.sh --offline       # pass -nr to Conan (air-gapped / warmed cache)
#   scripts/bootstrap.sh --skip-vendor   # do not run tools/vendor_export.py
#   scripts/bootstrap.sh --no-tests      # build only, do not run tests/smoke
#
# Requirements (checked below): gcc/g++ >= 16, cmake >= 4.2, conan >= 2.31,
# ninja, python3. Only the Conan profile name can be overridden
# (REFRAIN_CONAN_PROFILE); the tool versions are hard requirements.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PROFILE="${REFRAIN_CONAN_PROFILE:-gcc-release}"
CONAN_HOME_DIR="${CONAN_HOME:-$HOME/.conan2}"
JOBS="${JOBS:-$(nproc 2>/dev/null || echo 4)}"
OFFLINE=""
SKIP_VENDOR=""
NO_TESTS=""
PROFILE_ONLY=""

for arg in "$@"; do
    case "$arg" in
        --profile-only) PROFILE_ONLY=1 ;;
        --offline)     OFFLINE=1 ;;
        --skip-vendor) SKIP_VENDOR=1 ;;
        --no-tests)    NO_TESTS=1 ;;
        -h|--help)     sed -n '2,16p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 0 ;;
        *) echo "unknown option: $arg" >&2; exit 2 ;;
    esac
done

say() { printf '\n\033[1;36m== %s\033[0m\n' "$*"; }
die() { printf '\033[1;31mERROR: %s\033[0m\n' "$*" >&2; exit 1; }

version_ge() { # version_ge HAVE NEED -> true when HAVE >= NEED
    # A manual MAJOR.MINOR comparison misjudges versions without a dot ("4"
    # would be treated as satisfying "4.2"). `sort -V` is the canonical version
    # ordering on Linux (this script is Linux-only) and handles
    # prefixes/patch levels correctly.
    local have="$1" need="$2"
    [[ "$(printf '%s\n%s\n' "$need" "$have" | sort -V | head -1)" == "$need" ]]
}

say "checking toolchain"
command -v gcc >/dev/null || die "gcc not found"
command -v g++ >/dev/null || die "g++ not found"
command -v cmake >/dev/null || die "cmake not found"
command -v conan >/dev/null || die "conan not found (pip install conan==2.31.2)"
command -v ninja >/dev/null || die "ninja not found (apt install ninja-build)"
command -v python3 >/dev/null || die "python3 not found"

GCC_MAJOR="$(gcc -dumpversion | cut -d. -f1)"
(( GCC_MAJOR >= 16 )) || die "gcc >= 16 required (found $GCC_MAJOR)"
CMAKE_VER="$(cmake --version | head -1 | sed 's/.*version //')"
version_ge "$CMAKE_VER" "4.2" || die "cmake >= 4.2 required (found $CMAKE_VER)"
CONAN_VER="$(conan --version | sed 's/.* //')"
version_ge "$CONAN_VER" "2.31" || die "conan >= 2.31 required (found $CONAN_VER)"
NINJA_VER="$(ninja --version)"
printf '  gcc %s, cmake %s, conan %s, ninja %s\n' "$GCC_MAJOR" "$CMAKE_VER" "$CONAN_VER" "$NINJA_VER"

say "Conan profile '$PROFILE'"
PROFILE_FILE="$CONAN_HOME_DIR/profiles/$PROFILE"
if [[ -f "$PROFILE_FILE" ]]; then
    echo "  already exists: $PROFILE_FILE"
else
    mkdir -p "$CONAN_HOME_DIR/profiles"
    cat > "$PROFILE_FILE" <<EOF
# Refrain host profile (generated by scripts/bootstrap.sh)
[settings]
arch=x86_64
build_type=Release
compiler=gcc
compiler.cppstd=26
compiler.libcxx=libstdc++11
compiler.version=$GCC_MAJOR
os=Linux
[conf]
tools.cmake.cmaketoolchain:generator=Ninja
EOF
    echo "  created: $PROFILE_FILE"
fi
if [[ -n "$PROFILE_ONLY" ]]; then
    exit 0
fi

cd "$ROOT"

say "vendored recipes (conan/recipes -> local cache)"
if [[ -n "$SKIP_VENDOR" ]]; then
    echo "  skipped (--skip-vendor)"
else
    VENDOR_ARGS=(--build --profile "$PROFILE")
    if [[ -n "$OFFLINE" ]]; then
        VENDOR_ARGS+=(--offline)
    fi
    python3 tools/vendor_export.py "${VENDOR_ARGS[@]}"
fi

say "conan install"
# Explicit `if` (a failing `[[ ]] && ...` under `set -e` aborts the script with
# no message) and a mandatory lockfile.
LOCKFILE="conan/locks/vendor.lock"
if [[ ! -f "$LOCKFILE" ]]; then
    die "$LOCKFILE is missing; vendor dependencies must be pinned"
fi
OFFLINE_ARGS=()
if [[ -n "$OFFLINE" ]]; then
    OFFLINE_ARGS+=(-nr)
fi
conan install . -pr "$PROFILE" --build=missing --lockfile="$LOCKFILE" \
    "${OFFLINE_ARGS[@]}"

say "cmake configure + build ($JOBS jobs)"
cmake --preset conan-release
cmake --build --preset conan-release -j "$JOBS"

if [[ -n "$NO_TESTS" ]]; then
    say "done (tests skipped)"
    exit 0
fi

say "tests + smoke"
bash "$ROOT/scripts/ci.sh" --skip-configure --skip-build
